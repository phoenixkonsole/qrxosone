#!/bin/bash
# Configures the first stage: headless, no Python, Blender Internal only.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
W=${QRX_BLENDER_WORK:-/Users/pascalpapara/Documents/GitHub/qrxosone/.build/blender-2.79b}
SRC=$W/src/blender-2.79b
ROOT_SDK=/Users/pascalpapara/Documents/GitHub/qrxosone/.build/qrx-sdk/sdk/Development
OFF="WITH_PYTHON WITH_PYTHON_INSTALL WITH_GAMEENGINE WITH_PLAYER WITH_CYCLES WITH_OPENCOLORIO WITH_OPENSUBDIV
 WITH_OPENVDB WITH_AUDASPACE WITH_SDL WITH_OPENAL WITH_JACK WITH_CODEC_AVI WITH_CODEC_FFMPEG WITH_CODEC_SNDFILE
 WITH_IMAGE_OPENEXR WITH_IMAGE_OPENJPEG WITH_IMAGE_TIFF WITH_IMAGE_DDS WITH_IMAGE_CINEON WITH_IMAGE_HDR
 WITH_IMAGE_FRAMESERVER WITH_OPENIMAGEIO WITH_FREESTYLE WITH_COMPOSITOR WITH_BULLET WITH_MOD_FLUID WITH_MOD_SMOKE
 WITH_MOD_BOOLEAN WITH_MOD_REMESH WITH_MOD_OCEANSIM WITH_IK_ITASC WITH_IK_SOLVER WITH_LIBMV WITH_LIBMV_SCHUR_SPECIALIZATIONS
 WITH_OPENCOLLADA WITH_ALEMBIC WITH_INTERNATIONAL WITH_FFTW3 WITH_OPENMP WITH_BUILDINFO WITH_INPUT_NDOF
 WITH_RAYOPTIMIZATION WITH_LZO WITH_LZMA WITH_GTESTS WITH_SYSTEM_GLEW WITH_SYSTEM_OPENJPEG WITH_SYSTEM_BULLET
 WITH_X11 WITH_GAMEENGINE_DECKLINK WITH_INSTALL_PORTABLE WITH_LLVM WITH_CXX_GUARDEDALLOC WITH_ASSERT_ABORT WITH_GHOST_XDND"
A=(); for o in $OFF; do A+=("-D$o=OFF"); done
export PATH=/opt/homebrew/bin:$PATH
exec cmake -S "$SRC" -B "$W/build" -G Ninja -DCMAKE_TOOLCHAIN_FILE="$HERE/toolchain.cmake" \
  -DCMAKE_POLICY_VERSION_MINIMUM=3.5 -DCMAKE_BUILD_TYPE=Release -DCMAKE_EXPORT_COMPILE_COMMANDS=ON \
  -DCMAKE_C_FLAGS_RELEASE="-O2 -DNDEBUG" -DCMAKE_CXX_FLAGS_RELEASE="-O2 -DNDEBUG" \
  -DFREETYPE_LIBRARY=$ROOT_SDK/lib/libfreetype2.static.a -DWITH_HEADLESS=ON -DWITH_LEGACY_DEPSGRAPH=ON "${A[@]}" "$@"
