#!/usr/bin/env python3
"""Generates the stubs for what the first stage leaves out, from the linker's list of undefined
symbols: GHOST (no windows), GL and GLEW (no drawing). Each function ends the program with its name, and the
GLEW globals stay zero. `blender -b` calls none of them."""
import re, sys
from pathlib import Path
names = sorted(set(l.split()[-1] for l in Path(sys.argv[1]).read_text().splitlines() if l.strip()))
out = ['/* Generated by tools/blender/gen_missing.py. */', 'extern void qrx_missing(const char *name);']
# Stubs from an earlier run stay: a later link only lists what is still missing.
target = Path(sys.argv[2])
if target.exists():
    have = re.findall(r'\b(\w+)(?: = 0;|\(void\))', target.read_text())
    names = sorted(set(names) | {n for n in have if n != 'qrx_missing'})
keep = re.compile(r'^(GHOST_|gl[A-Z]|glu[A-Z]|glew|__glew|__GLEW_)')
for n in names:
    if not keep.match(n):
        print('not stubbed:', n)
    elif n.startswith('__GLEW_') or n == 'glewExperimental':
        out.append(f'unsigned char {n} = 0;')
    elif n.startswith('__glew'):
        out.append(f'void *{n} = 0;')
    else:
        out.append(f'long {n}(void) {{ qrx_missing("{n}"); return 0; }}')
Path(sys.argv[2]).write_text('\n'.join(out) + '\n')
print(len(out) - 2, 'stubs')
