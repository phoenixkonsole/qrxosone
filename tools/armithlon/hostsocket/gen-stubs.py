#!/usr/bin/env python3
"""Writes stubs.S for QRXHostSocket: one entry per LVO of bsdsocket.library that pushes the
register arguments (as clib/bsdsocket_protos.h names them) and calls the C function, plus the
vector table for MakeLibrary. The result goes to D0 and A0, so callers that read either work.
   gen-stubs.py OUT.S"""
import sys

# LVO: (C function, registers) for what QRXHostSocket.c implements
FUNCS = {
    5: ('c_socket', 'd0 d1 d2'), 6: ('c_bind', 'd0 a0 d1'), 7: ('c_listen', 'd0 d1'),
    8: ('c_accept', 'd0 a0 a1'), 9: ('c_connect', 'd0 a0 d1'), 10: ('c_sendto', 'd0 a0 d1 d2 a1 d3'),
    11: ('c_send', 'd0 a0 d1 d2'), 12: ('c_recvfrom', 'd0 a0 d1 d2 a1 a2'), 13: ('c_recv', 'd0 a0 d1 d2'),
    14: ('c_shutdown', 'd0 d1'), 15: ('c_setsockopt', 'd0 d1 d2 a0 d3'), 16: ('c_getsockopt', 'd0 d1 d2 a0 a1'),
    17: ('c_getsockname', 'd0 a0 a1'), 18: ('c_getpeername', 'd0 a0 a1'), 19: ('c_IoctlSocket', 'd0 d1 a0'),
    20: ('c_CloseSocket', 'd0'), 21: ('c_WaitSelect', 'd0 a0 a1 a2 a3 d1'), 22: ('c_SetSocketSignals', 'd0 d1 d2'),
    23: ('c_getdtablesize', ''), 27: ('c_Errno', ''), 28: ('c_SetErrnoPtr', 'a0 d0'), 29: ('c_Inet_NtoA', 'd0'),
    30: ('c_inet_addr', 'a0'), 31: ('c_Inet_LnaOf', 'd0'), 32: ('c_Inet_NetOf', 'd0'), 33: ('c_Inet_MakeAddr', 'd0 d1'),
    34: ('c_inet_network', 'a0'), 35: ('c_gethostbyname', 'a0'), 47: ('c_gethostname', 'a0 d0'),
    48: ('c_gethostid', ''), 49: ('c_SocketBaseTagList', 'a0'), 99: ('c_inet_aton', 'a0 a1'),
}
# void functions without an effect here
NOTHING = {43, 72, 76, 80, 81, 82, 84, 88, 90, 91, 93, 94, 96, 97}
LAST = 99

out = ['/* generated by gen-stubs.py */', '\t.text']
for lvo in range(5, LAST + 1):
    name, regs = FUNCS.get(lvo, ('c_nothing' if lvo in NOTHING else 'c_unimplemented', ''))
    regs = regs.split()
    out.append(f'\t.globl lvo_{lvo}\nlvo_{lvo}:')
    for r in reversed(regs):
        out.append(f'\tmove.l %{r},-(%sp)')
    out.append(f'\tjsr {name}')
    if regs:
        out.append(f'\tlea {4 * len(regs)}(%sp),%sp')
    out.append('\tmove.l %d0,%a0\n\trts')
# Open (a6 = base), Close, Expunge, the reserved one
out += ['\t.globl lvo_open\nlvo_open:', '\tmove.l %a6,-(%sp)', '\tjsr qrx_lib_open', '\taddq.l #4,%sp',
        '\tmove.l %d0,%a0\n\trts',
        '\t.globl lvo_close\nlvo_close:', '\tmove.l %a6,-(%sp)', '\tjsr qrx_lib_close', '\taddq.l #4,%sp', '\trts',
        '\t.globl lvo_zero\nlvo_zero:', '\tmoveq #0,%d0', '\tsub.l %a0,%a0', '\trts']
out += ['\t.data', '\t.align 2', '\t.globl qrx_hostsocket_vectors', 'qrx_hostsocket_vectors:',
        '\t.long lvo_open, lvo_close, lvo_zero, lvo_zero']
out += [f'\t.long lvo_{lvo}' for lvo in range(5, LAST + 1)]
out += ['\t.long -1', '']
open(sys.argv[1], 'w').write('\n'.join(out))
