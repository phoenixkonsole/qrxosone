#!/usr/bin/env python3
"""Generate a SYNTHETIC qrx_wallpaper.h for compile/emulator tests of QRXDesktop.

The real header (QRX artwork) is produced by the external QRX v0.20 payload
builder and is not part of the handoff.  This stub has the same symbols and
types: 640x512x8 planar data, a 224-entry palette and per-line RLE runs
(diagonal bands, ~40 runs per line, so the RTG renderer does realistic work)."""
import sys
W, H, DEPTH, COLORS = 640, 512, 8, 224
out = [ '/* SYNTHETIC TEST WALLPAPER - generated by gen-test-wallpaper.py, not QRX artwork */',
        '#define QRX_W %d' % W, '#define QRX_H %d' % H, '#define QRX_DEPTH %d' % DEPTH,
        '#define QRX_COLORS %d' % COLORS, '#define QRX_BYTES_PER_ROW %d' % (W // 8)]
pal = [((i * 3) % 256, (40 + i) % 256, (120 + i * 2) % 256) for i in range(COLORS)]
out.append('static const UBYTE qrx_palette[QRX_COLORS][3] = {' + ','.join('{%d,%d,%d}' % p for p in pal) + '};')
def pix(x, y): return ((x + y) // 16 + y // 64) % COLORS
planes = [bytearray(W // 8 * H) for _ in range(DEPTH)]
rle, offs = bytearray(), [0]
for y in range(H):
    row = [pix(x, y) for x in range(W)]
    for x, c in enumerate(row):
        for p in range(DEPTH):
            if c >> p & 1: planes[p][y * (W // 8) + x // 8] |= 0x80 >> (x % 8)
    x = 0
    while x < W:
        c, n = row[x], 1
        while x + n < W and row[x + n] == c and n < 255: n += 1
        rle += bytes([n, c]); x += n
    offs.append(len(rle))
def arr(b): return ','.join(str(v) for v in b)
out.append('static const UBYTE qrx_planes[QRX_DEPTH][QRX_BYTES_PER_ROW * QRX_H] = {' + ','.join('{' + arr(p) + '}' for p in planes) + '};')
out.append('static const ULONG qrx_rle_line_offset[QRX_H + 1] = {' + arr(offs) + '};')
out.append('static const UBYTE qrx_rle_data[%d] = {%s};' % (len(rle), arr(rle)))
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
print(f'runs per frame: {len(rle)//2}')
