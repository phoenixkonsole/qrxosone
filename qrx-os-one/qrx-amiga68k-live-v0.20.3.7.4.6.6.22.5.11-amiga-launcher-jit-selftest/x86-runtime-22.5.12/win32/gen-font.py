#!/usr/bin/env python3
"""Convert AROS/Amiga bitmap disk fonts (HUNK files, e.g. Fonts:arial/13 from the
AROS tree, AROS Public License) into a C header used by the qrx-win32 GDI.

usage: gen-font.py OUT.h NAME=path/to/fontfile [NAME=...]

The file layout is the classic DiskFontHeader: a code hunk starting with
MOVEQ #-1,D0; RTS, followed by the header and a struct TextFont whose pointers
are offsets relative to the hunk start (resolved by HUNK_RELOC32 at load time).
"""
import struct
import sys


def load_hunk(path):
    b = open(path, 'rb').read()
    assert struct.unpack_from('>I', b, 0)[0] == 0x3F3, 'not a HUNK file'
    o = 4
    while struct.unpack_from('>I', b, o)[0]:          # resident library names
        n = struct.unpack_from('>I', b, o)[0]
        o += 4 + n * 4
    o += 4
    tsize, first, last = struct.unpack_from('>III', b, o)
    o += 12 + (last - first + 1) * 4
    kind, n = struct.unpack_from('>II', b, o)
    assert kind & 0x3FFFFFFF in (0x3E9, 0x3EA), hex(kind)
    return b[o + 8:o + 8 + n * 4]


def parse(path):
    h = load_hunk(path)
    tf = 4 + 14 + 2 + 2 + 4 + 32             # code, Node, FileID, Revision, Segment, Name[32]
    tf += 20                                 # struct Message
    ysize, style, flags, xsize, baseline, smear, acc, lo, hi = struct.unpack_from('>HBBHHHHBB', h, tf)
    chardata, modulo, charloc, charspace, charkern = struct.unpack_from('>IHIII', h, tf + 14)
    n = hi - lo + 2                          # + the "not printable" glyph
    glyphs = []
    for i in range(n):
        off, width = struct.unpack_from('>HH', h, charloc + i * 4)
        space = struct.unpack_from('>h', h, charspace + i * 2)[0] if charspace else xsize
        kern = struct.unpack_from('>h', h, charkern + i * 2)[0] if charkern else 0
        rows = []
        for y in range(ysize):
            bits = 0
            for x in range(width):
                bit = off + x
                byte = h[chardata + y * modulo + (bit >> 3)]
                if byte & (0x80 >> (bit & 7)):
                    bits |= 1 << x
            rows.append(bits)
        glyphs.append((width, space, kern, rows))
    return dict(ysize=ysize, baseline=baseline, lo=lo, hi=hi, glyphs=glyphs, prop=bool(flags & 0x20))


def main():
    out = sys.argv[1]
    fonts = [a.split('=', 1) for a in sys.argv[2:]]
    w = ['/* Generated by gen-font.py from AROS bitmap fonts (AROS Public License). Do not edit. */\n',
         '#ifndef QRXWIN_FONTDATA_H\n#define QRXWIN_FONTDATA_H\n#include <stdint.h>\n',
         'typedef struct { uint8_t width; int8_t space, kern; uint32_t off; } qfont_glyph;\n',
         'typedef struct { const char *name; int height, baseline, lo, hi; const qfont_glyph *g; const uint32_t *rows; } qfont_data;\n']
    names = []
    for name, path in fonts:
        f = parse(path)
        rows = []
        gl = []
        for width, space, kern, r in f['glyphs']:
            gl.append(f'{{{width},{space},{kern},{len(rows)}}}')
            rows.extend(r)
        w.append(f'static const qfont_glyph {name}_g[{len(gl)}] = {{' + ','.join(gl) + '};\n')
        w.append(f'static const uint32_t {name}_rows[{len(rows)}] = {{' + ','.join(str(x) for x in rows) + '};\n')
        names.append(f'{{"{name}", {f["ysize"]}, {f["baseline"]}, {f["lo"]}, {f["hi"]}, {name}_g, {name}_rows}}')
    w.append(f'static const qfont_data qfont_table[{len(names)}] = {{\n  ' + ',\n  '.join(names) + '\n};\n')
    w.append(f'#define QFONT_COUNT {len(names)}\n#endif\n')
    open(out, 'w').write(''.join(w))


if __name__ == '__main__':
    main()
