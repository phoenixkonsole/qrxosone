#!/usr/bin/env python3
"""Write the header that gives 68100 core 1 its own copy of Musashi and the JIT.

  gen-core1-rename.py <libqrx_musashi.a> <output.h>

Musashi keeps its CPU in globals, so a second core running on another thread needs
a second copy. Every symbol the library defines, and the m68k_* callbacks it expects,
gets a qrx1_ prefix when compiled with `-include` of this header.
"""
import subprocess
import sys

lib, out = sys.argv[1:3]
text = subprocess.run(['nm', '-g', lib], check=True, capture_output=True, text=True).stdout
names = set()
for line in text.splitlines():
    parts = line.split()
    if len(parts) == 3 and parts[1] in 'TDBSCRWV':
        names.add(parts[2])
    elif len(parts) == 2 and parts[0] == 'U' and parts[1].lstrip('_').startswith('m68k_'):
        names.add(parts[1])
strip = sys.platform == 'darwin'
names = sorted(n[1:] if strip and n.startswith('_') else n for n in names)
# The JIT and the bus it calls are per core as well.
names += ['qrx_jit_init', 'qrx_jit_destroy', 'qrx_jit_report', 'qrx_jit_cpu_stopped',
          'qrx_jit_counters', 'qrx_full_bus_read', 'qrx_full_bus_write']
with open(out, 'w') as f:
    f.write('/* Generated by gen-core1-rename.py. */\n')
    for n in names:
        f.write(f'#define {n} qrx1_{n}\n')
