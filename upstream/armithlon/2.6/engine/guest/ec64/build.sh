#!/bin/sh
# Writes the program as C words for tests/ec64_tests.c.
set -e
cd "$(dirname "$0")"
m68k-elf-as -m68040 -o /tmp/fnv64.$$.o fnv64.S
m68k-elf-objcopy -O binary -j .text /tmp/fnv64.$$.o /tmp/fnv64.$$.bin
{ echo '/* Generated by guest/ec64/build.sh from fnv64.S. */'; xxd -i < /tmp/fnv64.$$.bin; } > ../../tests/ec64_fnv64.inc
rm -f /tmp/fnv64.$$.o /tmp/fnv64.$$.bin
